"""
Phenom Human Takeover Interceptor
Detects physical user mouse and keyboard actions during automation sessions.
Distinguishes synthetic inputs generated by Phenom from real user hardware inputs.
Pauses automation immediately (< 1 second) and requires an explicit continue/stop decision.
"""

import time
import asyncio
import threading
from contextlib import contextmanager
from typing import Optional, Callable, Dict, Any
import mouse
import keyboard

class HumanTakeoverAbort(Exception):
    pass

class HumanTakeoverManager:
    def __init__(self):
        self._is_automating = False
        self._is_paused = False
        self._is_synthetic = False
        self._synthetic_depth = 0
        self._lock = threading.Lock()
        self._on_takeover_callback: Optional[Callable[[], None]] = None
        self._last_takeover_time = 0.0

        # Register global OS hooks
        try:
            mouse.hook(self._on_mouse_event)
            keyboard.hook(self._on_keyboard_event)
        except Exception as e:
            # Fallback if hooks fail in certain non-interactive environments
            pass

    def set_takeover_callback(self, cb: Callable[[], None]):
        self._on_takeover_callback = cb

    @property
    def is_automating(self) -> bool:
        return self._is_automating

    @property
    def is_paused(self) -> bool:
        return self._is_paused

    def start_automation(self):
        with self._lock:
            self._is_automating = True
            self._is_paused = False

    def end_automation(self):
        with self._lock:
            self._is_automating = False
            self._is_paused = False

    @contextmanager
    def synthetic_action(self):
        """Context manager used whenever Phenom emits synthetic mouse/keyboard events."""
        with self._lock:
            self._synthetic_depth += 1
            self._is_synthetic = True
        try:
            yield
        finally:
            with self._lock:
                self._synthetic_depth = max(0, self._synthetic_depth - 1)
                if self._synthetic_depth == 0:
                    self._is_synthetic = False

    def _trigger_pause(self, source: str):
        with self._lock:
            if not self._is_automating or self._is_paused:
                return
            self._is_paused = True
            self._last_takeover_time = time.time()

        if self._on_takeover_callback:
            try:
                self._on_takeover_callback()
            except Exception:
                pass

    def _on_mouse_event(self, event):
        # If Phenom is executing a synthetic action, ignore
        if self._is_synthetic:
            return
        # If automation is active, user moved mouse or clicked
        if self._is_automating and not self._is_paused:
            self._trigger_pause(f"mouse_{type(event).__name__}")

    def _on_keyboard_event(self, event):
        if self._is_synthetic:
            return
        if self._is_automating and not self._is_paused:
            self._trigger_pause(f"key_{event.name}")

    async def wait_if_paused(self):
        """
        Called before and after every automation step.
        If user took over, pauses execution until decision is submitted.
        """
        while self._is_paused:
            if not self._is_automating:
                raise HumanTakeoverAbort("Automation aborted by user takeover.")
            await asyncio.sleep(0.05)

    def resolve_takeover(self, decision: str):
        """
        User decision: 'continue' or 'stop'.
        Never resumes without an explicit answer.
        """
        with self._lock:
            if decision == "continue":
                self._is_paused = False
            elif decision == "stop":
                self._is_automating = False
                self._is_paused = False
                raise HumanTakeoverAbort("Automation aborted by user takeover.")

takeover_manager = HumanTakeoverManager()
