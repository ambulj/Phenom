"""Phenom Pre-Meeting Autonomous Topic Research Swarm.

Coordinates headless Playwright workers via SwarmManager to compile pre-meeting
intelligence briefs, concept summaries, and agenda questions into Obsidian vault
notes without stealing OS focus or moving the cursor (WRK-01).
"""

from __future__ import annotations

import asyncio
from datetime import datetime, timezone
import logging
import os
import re
import time
from typing import Any, Dict, List, Optional, Set

from services.backend.automation.swarm_manager import swarm_manager
from services.backend.memory.vault import vault_manager, resolve_and_sandbox_vault_path
from services.backend.proactive.dispatcher import proactive_dispatcher, ProactiveCard, ProactivePriority
from services.backend.safety.action_log import action_log
from services.backend.safety.guardian import guardian

logger = logging.getLogger("phenom.topic_researcher")


class TopicResearchWorker:
    """Dispatches background headless workers to research topics for upcoming meetings."""

    def __init__(self) -> None:
        self._halted: bool = False
        self._prepared_event_ids: Set[str] = set()
        self._active_tasks: Dict[str, asyncio.Task] = {}

    @property
    def is_halted(self) -> bool:
        return self._halted

    def halt(self) -> None:
        """Synchronously halt all running research swarms in < 25ms SLA (SAF-02)."""
        self._halted = True
        for task_id, task in list(self._active_tasks.items()):
            if not task.done():
                task.cancel()
        self._active_tasks.clear()
        try:
            swarm_manager.abort_all("guardian_halt")
        except Exception as exc:
            logger.debug("SwarmManager abort during halt: %s", exc)

    def reset(self) -> None:
        """Reset halted state."""
        self._halted = False

    def is_event_prepared(self, event_id: str) -> bool:
        return event_id in self._prepared_event_ids

    def _sanitize_filename(self, text: str) -> str:
        """Sanitizes text for safe cross-platform file naming."""
        clean = re.sub(r'[\\/*?:"<>|]', "", text)
        clean = re.sub(r"\s+", " ", clean).strip()
        return clean[:60] if clean else "Meeting"

    def _generate_brief_content(
        self,
        topic: str,
        attendees: Optional[List[str]] = None,
        meeting_time: Optional[str] = None,
        web_snippets: Optional[List[Dict[str, Any]]] = None,
    ) -> str:
        """Formats comprehensive pre-meeting research brief markdown."""
        now_iso = datetime.now(timezone.utc).isoformat()
        attendees_str = ", ".join(attendees) if attendees else "None specified"
        meeting_time_str = meeting_time or "Upcoming"

        snippets_md = ""
        if web_snippets:
            for s in web_snippets:
                title = s.get("title", "Resource")
                url = s.get("url", "")
                snippet = s.get("snippet", "").strip()
                if url:
                    snippets_md += f"- **[{title}]({url})**\n  {snippet}\n\n"
                elif snippet:
                    snippets_md += f"- **{title}**: {snippet}\n\n"

        if not snippets_md:
            snippets_md = (
                f"- [[Architecture Overview]] - Technical reference for {topic}\n"
                f"- [[Project Roadmap]] - Related milestones and deliverables\n"
            )

        md = f"""---
title: "Meeting Brief: {topic}"
created: {now_iso}
topic: "{topic}"
author: Phenom Autonomous Research Swarm
tags:
  - meeting-brief
  - research
---

# Meeting Brief: {topic}

- **Scheduled Time**: {meeting_time_str}
- **Participants**: {attendees_str}
- **Status**: Autonomous Brief Ready

---

## 1. Executive Context & Objective
Preparation briefing synthesized for upcoming discussion on **{topic}**. Focus is on aligning core goals, reviewing prerequisite context, and identifying critical decisions.

## 2. Key Discussion Topics & Agenda
- [ ] Alignment on scope, target outcomes, and deadlines for {topic}.
- [ ] Identification of technical or operational dependencies.
- [ ] Resource allocation and next steps / action ownership.

## 3. Reference Materials & Background
{snippets_md.strip()}

---
*Auto-generated by Phenom Proactive Background Worker Swarm.*
"""
        return md

    async def research_topic(
        self,
        topic: str,
        attendees: Optional[List[str]] = None,
        meeting_time: Optional[str] = None,
        event_id: Optional[str] = None,
        use_headless_browser: bool = False,
        reference_urls: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """Dispatches autonomous topic research worker and commits brief note to vault."""
        if self._halted or guardian.is_halted:
            raise PermissionError("Topic research blocked: Guardian kill switch is active.")

        if not topic.strip():
            raise ValueError("Topic must not be empty.")

        task_id = f"research-{int(time.time() * 1000)}"
        logger.info("Starting topic research swarm for: %s (task: %s)", topic, task_id)

        web_snippets: List[Dict[str, Any]] = []

        # Headless Playwright worker integration if requested and URLs provided
        if use_headless_browser and reference_urls and not self._halted:
            for url in reference_urls[:3]:  # Bound scraping to top 3 links
                if self._halted or guardian.is_halted:
                    break
                try:
                    res = await swarm_manager.dispatch_task(
                        task_type="headless_browser",
                        payload={"url": url},
                        task_id=f"{task_id}-{len(web_snippets)}",
                    )
                    results = res.get("results", [])
                    if results and isinstance(results[0], dict):
                        web_snippets.append({
                            "title": results[0].get("title", topic),
                            "url": url,
                            "snippet": results[0].get("body_snippet", "")[:300],
                        })
                except Exception as exc:
                    logger.warning("Headless scraping failed for %s: %s", url, exc)

        if self._halted:
            return {"status": "aborted", "topic": topic, "reason": "guardian_halt"}

        # Format brief Markdown
        brief_md = self._generate_brief_content(
            topic=topic,
            attendees=attendees,
            meeting_time=meeting_time,
            web_snippets=web_snippets,
        )

        # Write to vault/Meetings/YYYY-MM-DD - {CleanTopic}.md
        today_str = datetime.now().strftime("%Y-%m-%d")
        clean_name = self._sanitize_filename(topic)
        filename = f"{today_str} - {clean_name}.md"

        meetings_dir = os.path.join(vault_manager.vault_path, "Meetings")
        os.makedirs(meetings_dir, exist_ok=True)

        target_file = resolve_and_sandbox_vault_path(
            os.path.join("Meetings", filename),
            vault_manager.vault_path,
        )

        with open(target_file, "w", encoding="utf-8") as f:
            f.write(brief_md)

        # Commit to vault git repo
        try:
            vault_manager.commit_changes(f"research: meeting brief for '{topic}'")
        except Exception as exc:
            logger.warning("Failed to commit meeting brief to git: %s", exc)

        rel_vault_path = os.path.relpath(target_file, vault_manager.vault_path)

        # Dispatch ProactiveCard for HUD
        card = ProactiveCard(
            event_type="MEETING_PREP",
            priority=ProactivePriority.NORMAL,
            title=f"Meeting Brief: {clean_name}",
            description=f"Autonomous research brief compiled for '{topic}' with agenda and reference notes.",
            action_chip="Open Brief",
            action_payload={"vault_file": rel_vault_path, "topic": topic},
        )
        try:
            await proactive_dispatcher.dispatch(card)
        except Exception as exc:
            logger.debug("Failed to dispatch proactive card: %s", exc)

        if event_id:
            self._prepared_event_ids.add(event_id)

        action_log.log_action(
            tool="topic_researcher",
            tier=1,
            args={"topic": topic, "event_id": event_id},
            decision="approved",
            result_status="SUCCESS",
        )

        return {
            "status": "ok",
            "topic": topic,
            "vault_file": rel_vault_path,
            "full_path": target_file,
            "card_id": card.id,
            "web_snippets_count": len(web_snippets),
        }


# Global singleton
topic_researcher = TopicResearchWorker()
