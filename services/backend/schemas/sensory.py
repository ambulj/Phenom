"""
Sensory Fabric & P2P Media Drop Schemas for Phenom Milestone 11.0 Phase 3
Defines Pydantic v2 models for:
- In-RAM companion camera streaming and VLM/OCR analysis contracts (SEN-01)
- AirDrop-style encrypted chunked media drop manifests, transfers, and acks (MSH-02)
- Safety registry tool argument schemas (SAF-01)
"""

from enum import Enum
from typing import List, Dict, Any, Optional, Literal
from pydantic import BaseModel, Field


class CameraAnalysisTask(str, Enum):
    OCR = "ocr"
    WHITEBOARD = "whiteboard"
    OBJECT = "object"


class CameraFramePayload(BaseModel):
    frame_id: str = Field(..., description="Unique frame identifier (UUID or sequential ID)")
    node_id: str = Field(..., description="Identifier of paired companion device transmitting frame")
    timestamp: float = Field(..., description="Capture timestamp in epoch seconds")
    image_base64: str = Field(..., description="JPEG image frame encoded as base64")
    width: int = Field(default=1280, description="Image frame pixel width")
    height: int = Field(default=720, description="Image frame pixel height")
    battery_level: Optional[float] = Field(default=None, description="Companion battery level (0.0 to 1.0 or 0 to 100)")
    is_charging: Optional[bool] = Field(default=False, description="Whether companion device is currently charging")
    wifi_rssi: Optional[int] = Field(default=None, description="Wi-Fi signal strength in dBm (e.g. -55)")
    format: str = Field(default="jpeg", description="Image encoding format (default 'jpeg')")


class CameraAnalysisRequest(BaseModel):
    task_type: CameraAnalysisTask = Field(default=CameraAnalysisTask.OBJECT, description="Vision task type: ocr, whiteboard, or object")
    prompt: Optional[str] = Field(default=None, description="Optional custom prompt or query for local VLM")
    node_id: Optional[str] = Field(default=None, description="Specific node ID to analyze, or None for latest active frame")


class CameraAnalysisResult(BaseModel):
    task_type: str = Field(..., description="Executed analysis task type")
    extracted_text: Optional[str] = Field(default=None, description="Text extracted via local OCR or whiteboard analysis")
    description: Optional[str] = Field(default=None, description="Object or scene description generated by local VLM")
    detected_items: List[Dict[str, Any]] = Field(default_factory=list, description="Structured bounding box or entity detections")
    model_used: str = Field(..., description="Local model or engine used (e.g. 'moondream2', 'easyocr')")
    processing_time_ms: float = Field(..., description="Elapsed execution latency in milliseconds")
    timestamp: float = Field(..., description="Execution completion timestamp")


class CameraStatus(BaseModel):
    is_streaming: bool = Field(default=False, description="Whether active frames are currently being received")
    node_id: Optional[str] = Field(default=None, description="ID of active streaming companion node")
    device_name: Optional[str] = Field(default=None, description="Human-readable device name")
    last_frame_ts: Optional[float] = Field(default=None, description="Timestamp of latest received frame")
    resolution: Optional[str] = Field(default=None, description="Latest frame resolution formatted as WxH")
    battery_level: Optional[float] = Field(default=None, description="Companion battery percentage")
    is_charging: Optional[bool] = Field(default=False, description="Companion charging state")
    wifi_rssi: Optional[int] = Field(default=None, description="Companion Wi-Fi RSSI in dBm")
    frames_received: int = Field(default=0, description="Total count of frames ingested since startup")
    is_halted: bool = Field(default=False, description="True if Guardian kill switch has halted camera ingestion")


class MediaDropDestination(str, Enum):
    VAULT = "vault"
    DOWNLOADS = "downloads"


class MediaDropTransferState(str, Enum):
    PENDING = "pending"
    TRANSFERRING = "transferring"
    COMPLETED = "completed"
    FAILED = "failed"
    ABORTED = "aborted"


class MediaDropManifest(BaseModel):
    transfer_id: str = Field(..., description="Unique transfer identifier (UUID)")
    source_node_id: str = Field(..., description="ID of sender device")
    target_node_id: str = Field(..., description="ID of destination device")
    filename: str = Field(..., description="Original filename without path components")
    file_size: int = Field(..., description="Total file size in bytes")
    sha256_checksum: str = Field(..., description="SHA-256 hex digest of the entire file")
    chunk_size: int = Field(default=65536, description="Chunk size in bytes (default 64 KB)")
    total_chunks: int = Field(..., description="Total number of chunks in transfer")
    destination: MediaDropDestination = Field(default=MediaDropDestination.DOWNLOADS, description="Target directory category")
    created_at: float = Field(..., description="Transfer creation timestamp in epoch seconds")


class MediaDropChunk(BaseModel):
    transfer_id: str = Field(..., description="Transfer ID this chunk belongs to")
    chunk_index: int = Field(..., description="0-indexed sequence position of this chunk")
    total_chunks: int = Field(..., description="Total chunks expected for transfer")
    data_base64: Optional[str] = Field(default=None, description="Base64-encoded chunk payload")
    data_size: int = Field(..., description="Byte length of raw chunk data")
    sha256_chunk: str = Field(..., description="SHA-256 hex digest of this individual chunk")


class MediaDropAck(BaseModel):
    transfer_id: str = Field(..., description="Transfer ID being acknowledged")
    chunk_index: int = Field(..., description="Chunk index acknowledged or completed")
    status: Literal["ack", "nack", "complete", "aborted"] = Field(default="ack", description="Acknowledgment status")
    bytes_received: int = Field(default=0, description="Cumulative bytes safely received and verified")
    error_message: Optional[str] = Field(default=None, description="Error explanation if status is nack or aborted")


class MediaDropTransfer(BaseModel):
    transfer_id: str = Field(..., description="Unique transfer ID")
    filename: str = Field(..., description="Filename being transferred")
    file_size: int = Field(..., description="Total file size in bytes")
    direction: Literal["incoming", "outgoing"] = Field(..., description="Transfer direction relative to this node")
    source_node_id: str = Field(..., description="Sender device ID")
    target_node_id: str = Field(..., description="Receiver device ID")
    destination: str = Field(..., description="Target destination folder identifier ('vault' or 'downloads')")
    state: MediaDropTransferState = Field(default=MediaDropTransferState.PENDING, description="Current lifecycle state")
    progress: float = Field(default=0.0, description="Transfer progress fraction (0.0 to 1.0)")
    bytes_transferred: int = Field(default=0, description="Number of bytes transferred so far")
    sha256_checksum: str = Field(..., description="Whole-file SHA-256 digest")
    error_message: Optional[str] = Field(default=None, description="Failure reason if state is failed or aborted")
    started_at: float = Field(..., description="Timestamp transfer started")
    completed_at: Optional[float] = Field(default=None, description="Timestamp transfer reached terminal state")
    saved_path: Optional[str] = Field(default=None, description="Absolute destination path if successfully completed")


# --- Tool Argument Schemas for Safety ToolRegistry (SAF-01) ---

class CameraGetFrameArgs(BaseModel):
    node_id: Optional[str] = Field(default=None, description="Optional companion device node ID to query")


class CameraAnalyzeArgs(BaseModel):
    task_type: Literal["ocr", "whiteboard", "object"] = Field(
        default="object",
        description="Vision inspection task: 'ocr' for printed text, 'whiteboard' for meeting/whiteboard notes, or 'object' for physical object query"
    )
    prompt: Optional[str] = Field(
        default=None,
        description="Optional custom query for local VLM (e.g. 'What cables are plugged into this switch?')"
    )


class MediaDropSendFileArgs(BaseModel):
    file_path: str = Field(..., description="Absolute path of the local file to send")
    target_node_id: str = Field(..., description="Target paired companion device node ID")
    destination: Literal["vault", "downloads"] = Field(
        default="downloads",
        description="Destination category on target device ('vault' for markdown notes or 'downloads' for general media)"
    )


class MediaDropGetHistoryArgs(BaseModel):
    limit: int = Field(default=20, description="Maximum number of recent transfer history records to return")
