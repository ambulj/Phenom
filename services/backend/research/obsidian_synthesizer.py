"""
Obsidian Vault Markdown Research Synthesizer (Phase 47-03, EXEC-05).
Compiles multi-source academic and web research into structured, verified Obsidian notes
with YAML frontmatter, executive summary, comparative matrix, and verified citations.
"""

import os
import re
from datetime import datetime, timezone
from typing import Optional, Dict, Any, List
from pydantic import BaseModel, Field

from services.backend.research.deep_research_crawler import CrawlResult, ResearchPaper, WebSnippet
from services.backend.safety.path_guard import validate_path


class SynthesizedReportResult(BaseModel):
    """Result payload of a synthesized Obsidian research note."""
    vault_file_path: str = Field(..., description="Absolute path to written Obsidian Markdown note")
    relative_path: str = Field(..., description="Relative path within the vault")
    title: str = Field(..., description="Report title")
    sources_count: int = Field(default=0, description="Total number of cited references")
    markdown_content: str = Field(default="", description="Full compiled Markdown text")


class ObsidianSynthesizer:
    """Formats and writes structured research reports into the Obsidian knowledge vault."""

    DEFAULT_VAULT_ROOT = os.path.join(
        os.environ.get("USERPROFILE") or os.path.expanduser("~"),
        "Documents",
        "Phenom",
        "vault"
    )

    def __init__(self, vault_root: Optional[str] = None):
        if vault_root:
            self.vault_root = os.path.abspath(vault_root)
        else:
            # Check if user profile vault exists, else fallback to project vault/
            candidate = os.path.abspath(self.DEFAULT_VAULT_ROOT)
            if os.path.exists(candidate):
                self.vault_root = candidate
            else:
                self.vault_root = os.path.abspath("vault")

        self.research_dir = os.path.join(self.vault_root, "Research")
        os.makedirs(self.research_dir, exist_ok=True)

    def compile_markdown_report(self, crawl_data: CrawlResult) -> str:
        """Assembles structured Markdown document with YAML frontmatter."""
        topic = crawl_data.query
        now = datetime.now(timezone.utc)
        date_str = now.strftime("%Y-%m-%d")
        iso_time = now.isoformat()

        paper_count = len(crawl_data.papers)
        web_count = len(crawl_data.web_snippets)
        total_sources = paper_count + web_count

        # Clean topic for tags
        tag_topic = re.sub(r"[^a-zA-Z0-9]+", "-", topic.lower()).strip("-")

        # 1. YAML Frontmatter
        frontmatter = (
            "---\n"
            f'title: "Deep Research: {topic}"\n'
            f'topic: "{topic}"\n'
            f"date: {date_str}\n"
            f"created_at: {iso_time}\n"
            f"sources_count: {total_sources}\n"
            f"academic_papers: {paper_count}\n"
            f"web_sources: {web_count}\n"
            f"tags: [research, sovereign-ai, {tag_topic}]\n"
            "status: verified\n"
            "---\n\n"
        )

        # 2. Header and Executive Summary
        body = [
            f"# Deep Research Report: {topic}\n",
            "> **Autonomous Research Briefing** — Generated by Phenom Sovereign Task Orchestrator.\n",
            "## 1. Executive Summary\n",
            f"{crawl_data.synthesis_summary}\n"
        ]

        # 3. Key Findings from Academic Publications
        body.append("## 2. Academic Discoveries & Methodologies\n")
        if crawl_data.papers:
            for idx, p in enumerate(crawl_data.papers, start=1):
                author_str = ", ".join(p.authors[:3]) + (" et al." if len(p.authors) > 3 else "")
                body.append(f"### 2.{idx}. {p.title}")
                body.append(f"**Authors:** {author_str} | **Published:** {p.published_date} | **Source:** {p.source.upper()}")
                if p.url:
                    body.append(f"**Direct Link:** [{p.url}]({p.url})")
                body.append(f"\n> {p.abstract}\n")
        else:
            body.append("*No academic papers were matched for this topic.*\n")

        # 4. Web & Documentation Findings
        if crawl_data.web_snippets:
            body.append("## 3. Web & Documentation Findings\n")
            for idx, w in enumerate(crawl_data.web_snippets, start=1):
                body.append(f"### 3.{idx}. {w.title}")
                body.append(f"**Domain:** `{w.domain}` | **URL:** [{w.url}]({w.url})")
                body.append(f"\n{w.content}\n")

        # 5. Comparative Synthesis Matrix
        body.append("## 4. Comparative Synthesis Matrix\n")
        if crawl_data.papers:
            body.append("| # | Title | Primary Focus / Mechanism | Date | Source |")
            body.append("|---|---|---|---|---|")
            for idx, p in enumerate(crawl_data.papers, start=1):
                short_title = (p.title[:45] + "...") if len(p.title) > 48 else p.title
                short_abs = (p.abstract[:60] + "...") if len(p.abstract) > 63 else p.abstract
                body.append(f"| {idx} | {short_title} | {short_abs} | {p.published_date} | {p.source} |")
            body.append("")

        # 6. Verified Citations
        body.append("## 5. Verified Citations & References\n")
        all_refs = []
        for p in crawl_data.papers:
            author_str = ", ".join(p.authors[:2]) if p.authors else "Unknown Authors"
            ref = f"- **{p.title}** ({p.published_date}). {author_str}. Available at: {p.url}"
            all_refs.append(ref)
        for w in crawl_data.web_snippets:
            ref = f"- **{w.title}** on `{w.domain}`. Retrieved from: {w.url}"
            all_refs.append(ref)

        if all_refs:
            body.extend(all_refs)
            body.append("")
        else:
            body.append("*No external references retrieved.*\n")

        full_md = frontmatter + "\n".join(body)
        return full_md

    def synthesize_and_save(
        self,
        crawl_data: CrawlResult,
        custom_filename: Optional[str] = None
    ) -> SynthesizedReportResult:
        """
        Compiles the research report and saves it directly to the Obsidian vault Research directory.
        """
        markdown_content = self.compile_markdown_report(crawl_data)

        topic = crawl_data.query
        safe_topic = re.sub(r"[^a-zA-Z0-9_\-]+", "_", topic.strip().lower())
        filename = custom_filename or f"research_{safe_topic}.md"
        if not filename.endswith(".md"):
            filename += ".md"

        target_file_path = os.path.join(self.research_dir, filename)

        # Enforce safety path allowlist
        validate_path(target_file_path, mode="write")

        with open(target_file_path, "w", encoding="utf-8") as f:
            f.write(markdown_content)

        rel_path = os.path.relpath(target_file_path, self.vault_root)

        return SynthesizedReportResult(
            vault_file_path=target_file_path,
            relative_path=rel_path,
            title=f"Deep Research: {topic}",
            sources_count=len(crawl_data.papers) + len(crawl_data.web_snippets),
            markdown_content=markdown_content
        )


# Global singleton instance
obsidian_synthesizer = ObsidianSynthesizer()
