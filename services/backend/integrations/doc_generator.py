"""
Phenom Document Generation Engine (Phase 5)
Creates documents in 4 formats:
1. Word (.docx) via python-docx
2. Excel (.xlsx) via openpyxl
3. PowerPoint (.pptx) via python-pptx
4. PDF (.pdf) via reportlab

Saves to a chosen folder and logs path and creation metadata.
"""

import os
from typing import Dict, Any, List, Optional
from datetime import datetime, timezone
import docx
from docx.shared import Inches, Pt, RGBColor
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
import pptx
from pptx.util import Inches as PptxInches, Pt as PptxPt
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

DEFAULT_DOCS_DIR = os.path.abspath("vault/documents")

class DocumentGenerator:
    def __init__(self, default_dir: Optional[str] = None):
        self.output_dir = default_dir or DEFAULT_DOCS_DIR
        os.makedirs(self.output_dir, exist_ok=True)

    def _resolve_path(self, filename: str, folder: Optional[str] = None) -> str:
        target_dir = folder or self.output_dir
        os.makedirs(target_dir, exist_ok=True)
        return os.path.join(target_dir, filename)

    # ---------------- 1. WORD DOCUMENT (.docx) ----------------
    def create_word_document(
        self,
        filename: str,
        title: str,
        sections: List[Dict[str, Any]],
        folder: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Creates a Word document with headings, paragraphs, and optional tables.
        sections: list of {'heading': str, 'content': str, 'bullets': list[str], 'table': list[list[str]]}
        """
        if not filename.endswith(".docx"):
            filename += ".docx"
        file_path = self._resolve_path(filename, folder)

        doc = docx.Document()
        
        # Title
        title_p = doc.add_heading(title, level=0)
        title_p.alignment = docx.enum.text.WD_ALIGN_PARAGRAPH.CENTER
        
        doc.add_paragraph(f"Generated by Phenom Assistant on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}")
        doc.add_paragraph("")

        for sec in sections:
            if "heading" in sec and sec["heading"]:
                doc.add_heading(sec["heading"], level=1)
            
            if "content" in sec and sec["content"]:
                doc.add_paragraph(sec["content"])

            if "bullets" in sec and sec["bullets"]:
                for bullet in sec["bullets"]:
                    doc.add_paragraph(bullet, style='List Bullet')

            if "table" in sec and sec["table"]:
                rows = sec["table"]
                if rows:
                    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
                    t.style = 'Table Grid'
                    for r_idx, row_data in enumerate(rows):
                        for c_idx, val in enumerate(row_data):
                            t.cell(r_idx, c_idx).text = str(val)

        doc.save(file_path)
        file_size = os.path.getsize(file_path)
        return {
            "format": "docx",
            "file_path": file_path,
            "filename": filename,
            "size_bytes": file_size,
            "sections_count": len(sections),
            "created_at": datetime.now(timezone.utc).isoformat()
        }

    # ---------------- 2. EXCEL SPREADSHEET (.xlsx) ----------------
    def create_excel_spreadsheet(
        self,
        filename: str,
        sheet_title: str,
        headers: List[str],
        rows: List[List[Any]],
        folder: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Creates an Excel spreadsheet with styled header row and auto-fit columns.
        """
        if not filename.endswith(".xlsx"):
            filename += ".xlsx"
        file_path = self._resolve_path(filename, folder)

        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = sheet_title[:31]  # Excel max sheet name length

        # Styles
        header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
        header_fill = PatternFill(start_color="1F497D", end_color="1F497D", fill_type="solid")
        thin_border = Border(
            left=Side(style='thin', color='D9D9D9'),
            right=Side(style='thin', color='D9D9D9'),
            top=Side(style='thin', color='D9D9D9'),
            bottom=Side(style='thin', color='D9D9D9')
        )

        # Write Headers
        ws.append(headers)
        for col_num in range(1, len(headers) + 1):
            cell = ws.cell(row=1, column=col_num)
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = Alignment(horizontal="center", vertical="center")

        # Write Data Rows
        for row_data in rows:
            ws.append(row_data)

        # Apply borders and auto column width
        for row in ws.iter_rows(min_row=1, max_row=len(rows) + 1, min_col=1, max_col=len(headers)):
            for cell in row:
                cell.border = thin_border

        for col in ws.columns:
            max_len = max(len(str(cell.value or '')) for cell in col)
            col_letter = openpyxl.utils.get_column_letter(col[0].column)
            ws.column_dimensions[col_letter].width = max(max_len + 3, 12)

        wb.save(file_path)
        file_size = os.path.getsize(file_path)
        return {
            "format": "xlsx",
            "file_path": file_path,
            "filename": filename,
            "size_bytes": file_size,
            "rows_count": len(rows),
            "columns_count": len(headers),
            "created_at": datetime.now(timezone.utc).isoformat()
        }

    # ---------------- 3. POWERPOINT PRESENTATION (.pptx) ----------------
    def create_powerpoint_presentation(
        self,
        filename: str,
        title: str,
        subtitle: str,
        slides_data: List[Dict[str, Any]],
        folder: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Creates a PowerPoint presentation with a title slide and content slides.
        slides_data: list of {'title': str, 'bullets': list[str]}
        """
        if not filename.endswith(".pptx"):
            filename += ".pptx"
        file_path = self._resolve_path(filename, folder)

        prs = pptx.Presentation()

        # Slide 1: Title slide layout (0)
        title_slide_layout = prs.slide_layouts[0]
        slide1 = prs.slides.add_slide(title_slide_layout)
        title_shape = slide1.shapes.title
        subtitle_shape = slide1.placeholders[1]
        title_shape.text = title
        subtitle_shape.text = subtitle

        # Subsequent slides: Bullet layout (1)
        bullet_slide_layout = prs.slide_layouts[1]
        for s_data in slides_data:
            slide = prs.slides.add_slide(bullet_slide_layout)
            shapes = slide.shapes
            title_box = shapes.title
            body_box = shapes.placeholders[1]
            title_box.text = s_data.get("title", "Slide")

            tf = body_box.text_frame
            bullets = s_data.get("bullets", [])
            if bullets:
                tf.text = bullets[0]
                for b_text in bullets[1:]:
                    p = tf.add_paragraph()
                    p.text = b_text

        prs.save(file_path)
        file_size = os.path.getsize(file_path)
        return {
            "format": "pptx",
            "file_path": file_path,
            "filename": filename,
            "size_bytes": file_size,
            "slides_count": len(slides_data) + 1,
            "created_at": datetime.now(timezone.utc).isoformat()
        }

    # ---------------- 4. PDF DOCUMENT (.pdf) ----------------
    def create_pdf_report(
        self,
        filename: str,
        title: str,
        paragraphs: List[str],
        table_data: Optional[List[List[str]]] = None,
        folder: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Creates a PDF document via reportlab with title, body text, and optional table.
        """
        if not filename.endswith(".pdf"):
            filename += ".pdf"
        file_path = self._resolve_path(filename, folder)

        doc = SimpleDocTemplate(file_path, pagesize=letter, rightMargin=54, leftMargin=54, topMargin=54, bottomMargin=54)
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            'CustomTitle',
            parent=styles['Heading1'],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#1A365D"),
            spaceAfter=14
        )
        body_style = ParagraphStyle(
            'CustomBody',
            parent=styles['Normal'],
            fontSize=11,
            leading=15,
            textColor=colors.HexColor("#2D3748"),
            spaceAfter=10
        )

        elements = []
        # Title
        elements.append(Paragraph(title, title_style))
        elements.append(Spacer(1, 10))

        # Paragraphs
        for p_text in paragraphs:
            elements.append(Paragraph(p_text, body_style))
            elements.append(Spacer(1, 8))

        # Table
        if table_data:
            elements.append(Spacer(1, 12))
            t = Table(table_data)
            t.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#2B6CB0")),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
                ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
                ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                ('FONTSIZE', (0, 0), (-1, -1), 10),
                ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
                ('BACKGROUND', (0, 1), (-1, -1), colors.HexColor("#F7FAFC")),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E0")),
            ]))
            elements.append(t)

        doc.build(elements)
        file_size = os.path.getsize(file_path)
        return {
            "format": "pdf",
            "file_path": file_path,
            "filename": filename,
            "size_bytes": file_size,
            "created_at": datetime.now(timezone.utc).isoformat()
        }

# Global document generator
doc_generator = DocumentGenerator()
